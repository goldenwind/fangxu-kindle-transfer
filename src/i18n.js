export function translateError(language, error) {
  const text = String(error?.message || error);
  if (language !== 'en') return text.replace('端口必须是 0 到 65535 的整数 / Port must be an integer from 0 to 65535', '端口必须是 0 到 65535 的整数');
  const operation = /^客户端操作失败 (\([^)]+\)): (.+)$/.exec(text);
  if (operation) return `Client operation failed ${operation[1]}: ${translateError(language, operation[2])}`;
  const existing = /^已有传书服务运行于 (.+)，请先关闭该服务$/.exec(text);
  if (existing) return `Another transfer service is running at ${existing[1]}. Stop it first.`;
  const prefix = Object.keys(errorMessages).sort((a, b) => b.length - a.length)
    .find(key => text === key || text.startsWith(`${key}:`) || text.startsWith(`${key} (`));
  return prefix ? errorMessages[prefix] + text.slice(prefix.length) : text;
}
export function translateLog(language, line) {
  const match = /^(\d{4}\/\d{2}\/\d{2} \d{2}:\d{2}:\d{2} )(.+)$/.exec(line);
  return match ? match[1] + translateError(language, match[2]) : translateError(language, line);
}
