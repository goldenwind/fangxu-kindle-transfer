// This key also matches the Kindle browser page. Storage may be unavailable.
export const languageStorageKey = 'fangxu-language';
export function normalizeLanguage(value) {
  if (value === 'zh' || value === 'zh-CN') return 'zh-CN';
  if (value === 'en') return 'en';
  return null;
}
export function initialLanguage(storage, browserLanguage = 'zh-CN', savedLanguage) {
  try {
    const saved = normalizeLanguage(storage?.getItem(languageStorageKey));
    if (saved) return saved;
  } catch { /* Follow the saved settings or system language without storage. */ }
  return normalizeLanguage(savedLanguage) || (String(browserLanguage).toLowerCase().startsWith('zh') ? 'zh-CN' : 'en');
}
export function rememberLanguage(storage, language) {
  try { storage?.setItem(languageStorageKey, language === 'en' ? 'en' : 'zh'); }
  catch { /* Switching remains available without storage. */ }
}
